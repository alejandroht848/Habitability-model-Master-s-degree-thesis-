import numpy as np
import matplotlib.pyplot as plt
import pandas as pd

# =========================================================================
# 1. FUNCIONES GALÁCTICAS Y ESTELARES
# =========================================================================

def m(feh):
    mu = 0.1
    sigma= 0.3
    return np.exp(-((feh - mu) ** 2) / (2 * (sigma) ** 2))

def sev(r_gal):
    Rd = 3.5
    return 1 - np.exp(-r_gal / Rd)

def grbev(r_gal):
    R_GRB = 2.15
    return 1 - np.exp(-R_GRB / r_gal)

def bev(d_sep):
    d0 = 1000
    return 1 - np.exp(-d_sep / d0)

def tf(T_eq):
    T_ideal = 290
    if 253 <= T_eq <= 303:
        return 1.0
    else:
        return max(0.0, 1 - abs(T_eq - T_ideal) / 100)

def calcular_rhz(dp, d_in, d_ex, T_eq):
    d_rhz = (d_in + d_ex) / 2
    score_distancia = 1 - abs(dp - d_rhz) / d_rhz
    return max(0.0, score_distancia) * tf(T_eq)

def limites_hz(L_star, T_eff):

    """Kopparapu et al. (2013)"""

    t_star = T_eff - 5780

    # Límite Interno
    s_eff_in = 1.0146 + 8.1884e-5 * t_star + 1.9394e-9 * (t_star**2) - 4.3618e-12 * (t_star**3)

    d_in = np.sqrt(L_star / s_eff_in)

    # Límite Externo
    s_eff_ex = 0.3507 + 5.1747e-5 * t_star + 1.2581e-9 * (t_star**2) - 2.1235e-12 * (t_star**3)

    d_ex = np.sqrt(L_star / s_eff_ex)

    return d_in, d_ex

def calcular_o(excentricidad):
    return 1 - excentricidad

def Hg(m_, sev_, grbev_, bev_):
    return 0.4 * m_ + 0.2 * sev_ + 0.2 * grbev_ + 0.2 * bev_

def He(rhz_, a_, o_, e_):
    return 0.4 * rhz_ + 0.1 * a_ + 0.25 * o_ + 0.25 * e_

def habitabilidad_total(Hg_, He_, Xg=0.25, Xe=0.75):
    return Xg * Hg_ + Xe * He_

